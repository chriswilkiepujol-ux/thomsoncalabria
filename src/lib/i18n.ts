export const LANGS = ["en", "es"] as const;
export type Lang = (typeof LANGS)[number];

export function isLang(v: string | undefined): v is Lang {
  return v === "en" || v === "es";
}

/** Public URL for a path in a language. English lives at the root, Spanish under /es. */
export function href(lang: Lang, path: string) {
  const p = path.startsWith("/") ? path : `/${path}`;
  if (lang === "en") return p;
  return p === "/" ? "/es" : `/es${p}`;
}

/** Metadata alternates: canonical + hreflang pairs for a page path (without language prefix). */
export function alternates(lang: Lang, path: string) {
  return {
    canonical: href(lang, path),
    languages: { en: href("en", path), es: href("es", path), "x-default": href("en", path) },
  };
}

